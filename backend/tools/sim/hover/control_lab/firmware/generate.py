"""Generate fixed 400 Hz SITL-only controller matrices; never writes to hardware."""
import json
import argparse
import sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lqg import LQG
HERE = Path(__file__).resolve().parent

def array(a):
    a = np.asarray(a)
    if a.ndim == 0:
        return f'{float(a):.17e}'
    return '{' + ','.join(array(x) for x in a) + '}'

specs = [('rp',73.5,(.25,.4)),('yaw',8.,(.08,.1))]
banks = (.01,.001,.0001)
parser=argparse.ArgumentParser();parser.add_argument('--gyro-delay',type=float,choices=(0.,.0075),default=.0075)
parser.add_argument('--motor-delay',type=float,choices=(.03,.045),default=.03)
parser.add_argument('--motor-tau',type=float,choices=(.015,.025),default=.015)
args=parser.parse_args();gyro_delay=args.gyro_delay
models = [[LQG(.0025,K=k,dist_sigma=s,effort=e,rate_cost=.0001,gyro_delay=gyro_delay,delay=args.motor_delay,tau=args.motor_tau) for e in banks] for _,k,s in specs]
n=models[0][0].A.shape[0];gyro_index=n-1 if gyro_delay else 5
lines = ['// Generated by generate.py. Offline simulation only.', '#pragma once', 'namespace PacketLQG {', f'constexpr int N={n};', 'constexpr int BANKS=3;', f'constexpr int GYRO_INDEX={gyro_index};', f'constexpr int QUEUE_LAST={5+round(args.motor_delay/.0025)};']
for field,shape in [('A',f'[2][{n}][{n}]'),('gain',f'[2][{n}][2]')]:
    lines.append(f'static const double {field}{shape} = '+array([getattr(row[0],field) for row in models])+';')
lines.append(f'static const double feedback[2][3][{n}] = '+array([[m.feedback[0] for m in row] for row in models])+';')
lines.append('}')
(HERE/'PacketLQGMatrices.h').write_text('\n'.join(lines)+'\n')
(HERE/'matrices.json').write_text(json.dumps({'dt':.0025,'delay':args.motor_delay,'tau':args.motor_tau,'gyro_delay':gyro_delay,'banks_effort':banks,'rate_cost':.0001,'models':[{'name':name,'K':k,'dist_sigma':s} for name,k,s in specs]},indent=2)+'\n')
